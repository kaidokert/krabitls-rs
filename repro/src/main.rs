type U2048 = FixedUInt<u32, 64>;

/// Mirrors `krabitls::backends::rsa_verify::VkPair` exactly.
struct VkPair<T>
where
    T: ModMathInt,
{
    pkcs1: Pkcs1Vk<Sha256, ModMathValue<T>, ModMathParams<T>>,
    pss: PssVk<Sha256, ModMathValue<T>, ModMathParams<T>>,
}

enum RsaVk {
    U2048(VkPair<U2048>),
}

/// Mirrors `build_vk_pair` from krabitls. Does NOT have `#[inline(never)]`
/// — that's the workaround. Removing it is what makes bug 2 fire.
fn build_vk_pair<T>(modulus: &[u8], exponent: u32) -> Option<VkPair<T>>
where
    T: ModMathInt,
{
    let key = public_key_from_be_bytes::<T>(modulus, exponent).ok()?;
    let pkcs1 = Pkcs1Vk::<Sha256, _, _>::new(key.clone());
    let pss = PssVk::<Sha256, _, _>::new(key);
    Some(VkPair { pkcs1, pss })
}

/// Single combined function holding `build_vk_pair` + `RsaVerifierKey::new`
/// dispatch + PSS verify. This is the shape krabitls's caller flattens to
/// when LLVM inlines `build_vk_pair` into `RsaVerifierKey::new` and that
/// into `verify_server_flight`'s caller chain. `#[inline(never)]` keeps
/// it as a single TU-visible function so `main` calls it through a real
/// function boundary.
#[inline(never)]
fn build_and_verify(modulus: &[u8], exponent: u32, msg: &[u8], sig_bytes: &[u8]) -> bool {
    let vk = match modulus.len() {
        256 => match build_vk_pair::<U2048>(modulus, exponent) {
            Some(v) => RsaVk::U2048(v),
            None => return false,
        },
        _ => return false,
    };
    let prehash = Sha256::digest(msg);
    match &vk {
        RsaVk::U2048(vks) => {
            if sig_bytes.len() != 256 {
                return false;
            }
            let sig = PssSig::from(U2048::from_be_bytes(sig_bytes));
            vks.pss.verify_prehash(&prehash, &sig).is_ok()
        }
    }
}

